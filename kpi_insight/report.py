"""Render a brief + facts as Markdown."""
from __future__ import annotations

import os
from pathlib import Path

from .narrative import BriefResult


def _fmt(x, unit: str) -> str:
    return f"{x:.1f}%" if unit == "percent" else f"{int(x):,}"


def render_markdown(facts: dict, result: BriefResult, images: dict[str, Path] | None = None,
                    report_dir: Path | None = None) -> str:
    b = result.brief
    lines = [f"# {b.title}", "",
             f"*Vertical:* `{facts['vertical']}` | *Date:* {facts['date']} | "
             f"*Compared with:* {facts['compare_date']} (same day previous month) | "
             f"*Narrative source:* `{result.source}` | *Data:* synthetic", "",
             "## Summary", "", b.summary, "", "## Drivers", ""]
    lines += [f"- {d}" for d in b.drivers]
    lines += ["", "## Recommendations", ""]
    lines += [f"- {r}" for r in b.recommendations]

    lines += ["", "## KPI table", "",
              "| KPI | Basis | Current | Same day last month | Change | Change % | Month-end forecast | Trend (180d) |",
              "|---|---|---:|---:|---:|---:|---:|---|"]
    for k, v in facts["kpis"].items():
        unit = v["unit"]
        chg = f"{v['change']:+.1f} pp" if v["change_unit"] == "pp" else f"{v['change']:+,}"
        t = v.get("trend")
        trend = f"{t['direction']}, {t['strength']}, momentum {t['momentum']}" if t else "-"
        fc = _fmt(v["month_end_forecast"], unit)
        if "month_end_forecast_formula" in v:
            fc += f" (formula: {v['month_end_forecast_formula']:,})"
        lines.append(f"| {v['label']} | {v['basis']} | {_fmt(v['current'], unit)} | "
                     f"{_fmt(v['previous_month_same_day'], unit)} | {chg} | {v['change_pct']:+.1f}% | {fc} | {trend} |")

    if images:
        rel = lambda p: Path(os.path.relpath(p, report_dir)).as_posix() if report_dir else Path(p).as_posix()  # noqa: E731
        lines += ["", "## Charts", ""]
        lines += [f"![{name}]({rel(p)})" for name, p in images.items()]

    lines += ["", "## Top movers", ""]
    for key, m in facts["movers"].items():
        unit = "pp" if m["unit"] == "pp" else ""
        lines += [f"**{facts['kpis'][m['kpi']]['label']} by {m['dimension']}** "
                  f"(net change {m['total_change']:+,}{' ' + unit if unit else ''}; members <2% of size filtered: {m['filtered_members']})", "",
                  "| Member | Contribution | Share of net change | Share of gross movement | Previous | Current |",
                  "|---|---:|---:|---:|---:|---:|"]
        for r in m["top"]:
            c = f"{r['contribution']:+.2f} pp" if unit else f"{r['contribution']:+,}"
            pv = f"{r['value_prev']:.1f}%" if unit else f"{r['value_prev']:,}"
            cv = f"{r['value_curr']:.1f}%" if unit else f"{r['value_curr']:,}"
            lines.append(f"| {r['member']} | {c} | {r['share_of_change_pct']:.1f}% | "
                         f"{r['share_of_gross_movement_pct']:.1f}% | {pv} | {cv} |")
        lines.append("")
    lines += ["---", "*Generated by kpi-insight-engine on synthetic data. Every number above comes from the "
              "computed facts; the narrative is checked by a numeric guardrail.*", ""]
    return "\n".join(lines)
